-- A bill's id is its variable symbol, so it starts where a symbol looks like one.
create table if not exists bill (
    id           bigint generated by default as identity (start with 1000) primary key,
    amount       decimal(12, 2) not null check (amount > 0),
    currency     char(3)        not null,
    created_at   timestamp with time zone not null,
    -- One payment pays one bill: the database refuses the second, whatever the app does.
    paid_by      varchar(40) unique,
    paid_seen_at timestamp with time zone,
    version      integer
);
